"""parlando menu bar app.

Runs the dictation engine in the background; the menu bar offers start/stop,
language switching, Enter mode and quit. No terminal window needed.

Usage:
    parlando                   # start in the menu bar (the default of `parlando`)
    parlando --install-app     # create ~/Applications/Parlando.app (recommended)
    parlando --uninstall-app
    parlando --install-login   # auto-start at login (opens Parlando.app)
    parlando --uninstall-login
    parlando-menubar           # same app; kept as an alias

Why an app bundle: macOS ties Microphone and Accessibility permissions to
the *responsible* application. Run from a terminal, that is Terminal/iTerm/
VS Code, which is confusing and breaks whenever you switch terminals.
`--install-app` writes a thin bundle (Info.plist, icon, a prebuilt Mach-O
stub and a launch script) that runs this package's Python; launched from
Finder, Spotlight or the LaunchAgent, permissions are then requested and
stored as "Parlando".

Menu bar icon (template, adapts to light/dark): three-bar waveform = ready,
waveform with a dot = recording, two equal bars = paused. A small badge
next to it shows a non-default language (ᵉⁿ / ᵗʳ), model download
progress, or a problem (!). The menu opens with a status block (what
parlando is doing, a hint, and a one-click fix when a permission is
missing). The global hotkey works too (default: single tap of right
Option).
"""

from __future__ import annotations

import asyncio
import os
import plistlib
import shutil
import subprocess
import sys
import threading
from pathlib import Path

from parlando import engine

BUNDLE_ID = "com.parlando.menubar"
APP_BUNDLE = Path.home() / "Applications" / "Parlando.app"
LAUNCH_AGENT = Path.home() / "Library" / "LaunchAgents" / f"{BUNDLE_ID}.plist"
APP_LOG = Path.home() / "Library" / "Logs" / "parlando-app.log"

LANGUAGES = {
    "Türkçe": "Turkish",
    "English": "English",
}
# Superscript badge shown next to the icon when the language is not the
# default (Config.language).
LANGUAGE_BADGES = {"Turkish": "ᵗʳ", "English": "ᵉⁿ"}

# Template icons (black + alpha): macOS recolors them to match the menu bar
# in light and dark mode. Regenerate with scripts/make_icons.py.
_ASSETS = Path(__file__).resolve().parent / "assets"
ICONS = {
    "idle": str(_ASSETS / "mic.png"),
    "recording": str(_ASSETS / "mic-recording.png"),
    "paused": str(_ASSETS / "mic-paused.png"),
}
APP_ICNS = _ASSETS / "Parlando.icns"
# Prebuilt Mach-O stub (scripts/launcher.c): macOS will not launch a bundle
# whose main executable is a script, so this binary runs launch.sh as a
# child and waits (see launcher.c for why not exec).
APP_LAUNCHER_BIN = _ASSETS / "parlando-launcher"


# -----------------------------------------------------------------------------
# App bundle (~/Applications/Parlando.app)
# -----------------------------------------------------------------------------

# launch.sh execs the interpreter that owns this package: an absolute path
# (uv tool or a venv, for --install-app) or a path relative to
# Contents/Resources (the embedded runtime of a distributable build made by
# scripts/build_app.sh). Using `python -m` rather than the console script
# keeps it valid across reinstalls. stdout/stderr go to a log: there is no
# terminal.
_LAUNCH_SH = """#!/bin/sh
# Parlando.app launch script, generated by parlando ({origin}).
RES=$(cd "$(dirname "$0")" && pwd)
PARLANDO_APP_BUNDLE=$(cd "$RES/../.." && pwd); export PARLANDO_APP_BUNDLE
exec {python} -m parlando.menubar "$@" >>"$HOME/Library/Logs/parlando-app.log" 2>&1
"""


def bundle_plist(version: str = "1.0") -> dict:
    # --install-app deliberately passes no package version: that bundle is
    # only a launcher, and ad-hoc signed bundles are identified by content
    # hash in the privacy database, so a stable bundle keeps granted
    # permissions valid across `uv tool upgrade parlando`. Distributable
    # builds (scripts/build_app.sh) carry the real version: every release
    # is a new bundle anyway.
    return {
        "CFBundleName": "Parlando",
        "CFBundleDisplayName": "Parlando",
        "CFBundleIdentifier": BUNDLE_ID,
        "CFBundleExecutable": "parlando",
        "CFBundleIconFile": "Parlando",
        "CFBundlePackageType": "APPL",
        "CFBundleShortVersionString": version,
        "CFBundleVersion": version,
        "CFBundleInfoDictionaryVersion": "6.0",
        "LSMinimumSystemVersion": "13.0",
        "LSUIElement": True,  # menu bar only: no Dock icon, no app switcher
        "NSHighResolutionCapable": True,
        "NSHumanReadableCopyright": "MIT License",
        "NSMicrophoneUsageDescription": (
            "Parlando listens to your voice to type what you say. "
            "Audio never leaves this Mac."
        ),
    }


def build_app_bundle(
    dest: Path,
    python: str | None = None,
    sign: bool = True,
    version: str = "1.0",
) -> Path:
    """Write a minimal .app at `dest` (replacing any existing one).

    `python`: absolute interpreter path, or a path relative to
    Contents/Resources for a runtime embedded in the bundle.
    """
    python = python or sys.executable
    if Path(python).is_absolute():
        py_expr, origin = _sh_quote(python), "--install-app"
    else:
        py_expr, origin = '"$RES"/' + _sh_quote(python), "scripts/build_app.sh"
    contents = dest / "Contents"
    macos = contents / "MacOS"
    resources = contents / "Resources"
    if dest.exists():
        shutil.rmtree(dest)
    macos.mkdir(parents=True)
    resources.mkdir(parents=True)

    with open(contents / "Info.plist", "wb") as fh:
        plistlib.dump(bundle_plist(version), fh)
    exe = macos / "parlando"
    shutil.copyfile(APP_LAUNCHER_BIN, exe)
    exe.chmod(0o755)
    script = resources / "launch.sh"
    script.write_text(_LAUNCH_SH.format(python=py_expr, origin=origin))
    script.chmod(0o755)
    shutil.copyfile(APP_ICNS, resources / "Parlando.icns")

    if sign:
        # Ad-hoc signature: no certificate needed. It gives the bundle a
        # stable identity for the privacy (TCC) database.
        subprocess.run(
            ["codesign", "--force", "--deep", "--sign", "-",
             "--identifier", BUNDLE_ID, str(dest)],
            check=True,
            capture_output=True,
        )
    return dest


def _sh_quote(path: str) -> str:
    return "'" + path.replace("'", "'\\''") + "'"


_LSREGISTER = (
    "/System/Library/Frameworks/CoreServices.framework/Frameworks/"
    "LaunchServices.framework/Support/lsregister"
)


def install_app() -> int:
    build_app_bundle(APP_BUNDLE)
    # Register with LaunchServices so Spotlight/Finder show the name and
    # icon immediately instead of after the next indexing pass.
    if os.path.exists(_LSREGISTER):
        subprocess.run([_LSREGISTER, "-f", str(APP_BUNDLE)], check=False, capture_output=True)
    print(
        f"Installed: {APP_BUNDLE}\n"
        "Open it from Finder or Spotlight (\"Parlando\"). macOS will ask for "
        "Microphone and Accessibility permissions in the name of Parlando; "
        "grant both; Parlando picks them up without a restart.\n"
        f"App output goes to {APP_LOG}"
    )
    return 0


def uninstall_app() -> int:
    if LAUNCH_AGENT.exists():
        uninstall_login()
    if APP_BUNDLE.exists():
        shutil.rmtree(APP_BUNDLE)
        print(f"Removed {APP_BUNDLE}")
    else:
        print("Not installed.")
    return 0


# -----------------------------------------------------------------------------
# Start at login (LaunchAgent)
# -----------------------------------------------------------------------------


def install_login() -> int:
    # Launch through the app bundle so permissions belong to "Parlando",
    # not to a bare python binary. Build it only if missing: rewriting a
    # bundle changes its hash and would invalidate granted permissions.
    if not APP_BUNDLE.exists():
        build_app_bundle(APP_BUNDLE)
        print(f"Created {APP_BUNDLE}")
    plist = {
        "Label": BUNDLE_ID,
        "ProgramArguments": ["/usr/bin/open", "-g", str(APP_BUNDLE)],
        "RunAtLoad": True,
        "KeepAlive": False,
        "StandardErrorPath": str(Path.home() / "Library/Logs/parlando-agent.log"),
    }
    LAUNCH_AGENT.parent.mkdir(parents=True, exist_ok=True)
    with open(LAUNCH_AGENT, "wb") as fh:
        plistlib.dump(plist, fh)
    subprocess.run(["launchctl", "unload", str(LAUNCH_AGENT)], capture_output=True)
    subprocess.run(["launchctl", "load", str(LAUNCH_AGENT)], check=False)
    print(f"Installed: {LAUNCH_AGENT}\nparlando will start at your next login.")
    return 0


def uninstall_login() -> int:
    subprocess.run(["launchctl", "unload", str(LAUNCH_AGENT)], capture_output=True)
    if LAUNCH_AGENT.exists():
        LAUNCH_AGENT.unlink()
        print("Uninstalled.")
    else:
        print("Not installed.")
    return 0


# -----------------------------------------------------------------------------
# Relaunch guard: survive the kill macOS does when Accessibility is toggled
# -----------------------------------------------------------------------------

GUARD_LABEL = "com.parlando.relaunch-guard"
GUARD_PLIST = Path.home() / "Library" / "Application Support" / "parlando" / "relaunch-guard.plist"


def app_bundle_path() -> Path | None:
    """The .app we run from (launch.sh exports it), or None from a terminal."""
    p = os.environ.get("PARLANDO_APP_BUNDLE")
    return Path(p) if p and p.endswith(".app") else None


def guard_plist(label: str, pid: int, app: Path) -> dict:
    # launchd runs this outside the app's process group, so it survives
    # when macOS terminates the app on the Accessibility switch. It waits
    # for the app to be gone and opens it again (LaunchServices launch, so
    # permissions still belong to Parlando).
    script = (
        f"while kill -0 {pid} 2>/dev/null; do sleep 0.5; done; sleep 1; "
        f"/usr/bin/open -g {_sh_quote(str(app))}"
    )
    return {
        "Label": label,
        "ProgramArguments": ["/bin/sh", "-c", script],
        "RunAtLoad": True,
        "KeepAlive": False,
    }


class RelaunchGuard:
    """Registers/removes the launchd job around the permission grant.

    Active only while the Accessibility problem is showing. Stopped when
    the permission arrives (the app keeps running) and on a normal quit
    (so quitting never respawns the app). If macOS kills the app instead,
    the guard fires and the app comes back already trusted.
    """

    def __init__(self, app: Path | None) -> None:
        self.app = app
        self.active = False

    def _domain(self) -> str:
        return f"gui/{os.getuid()}"

    def start(self) -> None:
        if self.active or self.app is None:
            return
        GUARD_PLIST.parent.mkdir(parents=True, exist_ok=True)
        with open(GUARD_PLIST, "wb") as fh:
            plistlib.dump(guard_plist(GUARD_LABEL, os.getpid(), self.app), fh)
        subprocess.run(["launchctl", "bootout", f"{self._domain()}/{GUARD_LABEL}"],
                       capture_output=True)
        r = subprocess.run(["launchctl", "bootstrap", self._domain(), str(GUARD_PLIST)],
                           capture_output=True, text=True)
        self.active = r.returncode == 0
        if self.active:
            engine.LOGGER.info("relaunch guard armed (pid %d)", os.getpid())
        else:
            engine.LOGGER.warning("relaunch guard failed: %s", r.stderr.strip())

    def stop(self) -> None:
        if not self.active:
            return
        self.cleanup()
        self.active = False
        engine.LOGGER.info("relaunch guard disarmed")

    def cleanup(self) -> None:
        """Remove a finished or stale job (e.g. the one that relaunched us)."""
        subprocess.run(["launchctl", "bootout", f"{self._domain()}/{GUARD_LABEL}"],
                       capture_output=True)


