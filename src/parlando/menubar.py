def run_menubar() -> int:
    import rumps

    engine_holder: dict = {"engine": None}

    class ParlandoApp(rumps.App):
        def __init__(self) -> None:
            super().__init__(
                "parlando",
                title=None,
                icon=ICONS["idle"],
                template=True,
                quit_button=None,
            )
            self._icon_state = "idle"
            self._ax_alerted = False
            self._guard = RelaunchGuard(app_bundle_path())
            self._guard.cleanup()
            # Status block: two text lines (disabled items) and an action
            # line that appears only when something needs the user.
            self.status_item = rumps.MenuItem("Starting up…")
            self.detail_item = rumps.MenuItem("")
            self.action_item = rumps.MenuItem("", callback=self.on_action)
            self._action_target = None
            self.toggle_item = rumps.MenuItem(
                "Start recording", callback=self.on_toggle
            )
            self.enter_item = rumps.MenuItem(
                "Press Enter after each utterance", callback=self.on_enter_mode
            )
            self.lang_items = {
                asr_name: rumps.MenuItem(label, callback=self.on_language)
                for label, asr_name in LANGUAGES.items()
            }
            self.menu = [
                self.status_item,
                self.detail_item,
                self.action_item,
                None,
                self.toggle_item,
                self.enter_item,
                {"Language": list(self.lang_items.values())},
                {"Vocabulary": [
                    rumps.MenuItem("Add Term…", callback=self.on_vocab_add),
                    rumps.MenuItem(
                        "Edit Vocabulary File…", callback=self.on_vocab_edit
                    ),
                ]},
                None,
                rumps.MenuItem("Open log file", callback=self.on_log),
                rumps.MenuItem("Quit", callback=self.on_quit),
            ]
            self._set_hidden(self.action_item, True)
            self._set_hidden(self.detail_item, True)
            # UI updates must happen on the main thread: polling engine state
            # from a main-loop timer is the thread-safe pattern.
            self._poll = rumps.Timer(self._refresh, 0.5)
            self._poll.start()

        @staticmethod
        def _set_hidden(item, hidden: bool) -> None:
            item._menuitem.setHidden_(hidden)

        @staticmethod
        def _set_title(item, title: str) -> None:
            if item.title != title:
                item.title = title

        def _set_icon(self, state: str) -> None:
            if state != self._icon_state:
                self._icon_state = state
                self.icon = ICONS[state]

        def _refresh(self, _timer) -> None:
            eng = engine_holder.get("engine")
            if eng is None:
                return
            if "accessibility" in eng.status.problems:
                self._guard.start()
            else:
                self._guard.stop()
            if eng.accessibility_missing and not self._ax_alerted:
                # No terminal to read the warning: say it once in a dialog.
                self._ax_alerted = True
                rumps.alert(
                    title="Parlando needs Accessibility access",
                    message=(
                        "Without it the hotkey cannot be heard and text cannot "
                        "be typed.\n\nSystem Settings > Privacy & Security > "
                        "Accessibility: enable Parlando (or the terminal you "
                        "started it from). Parlando picks it up by itself, "
                        "and reopens itself if macOS quits it when you flip "
                        "the switch."
                    ),
                )
            for lang, item in self.lang_items.items():
                item.state = int(eng.cfg.language == lang)

            view = describe_status(eng)
            if self.title != view["badge"]:
                self.title = view["badge"]
            self._set_icon(view["icon"])
            self._set_title(self.status_item, view["primary"])
            self._set_title(self.detail_item, view["secondary"])
            self._set_hidden(self.detail_item, not view["secondary"])
            action = view["action"]
            if action != self._action_target:
                self._action_target = action
                self._set_hidden(self.action_item, action is None)
                if action:
                    self._set_title(self.action_item, _PROBLEM_TEXT[action][2])
            self._set_title(self.toggle_item, view["toggle"])
            if bool(self.toggle_item.callback) != view["can_toggle"]:
                self.toggle_item.set_callback(self.on_toggle if view["can_toggle"] else None)

        def on_action(self, _item) -> None:
            pane = SETTINGS_PANES.get(self._action_target or "")
            if pane:
                subprocess.run(["open", pane], check=False)

        def on_toggle(self, _item) -> None:
            eng = engine_holder["engine"]
            if eng:
                eng.request_toggle()

        def on_enter_mode(self, item) -> None:
            eng = engine_holder["engine"]
            if eng:
                eng.cfg.send_enter = not eng.cfg.send_enter
                item.state = eng.cfg.send_enter

        def on_language(self, item) -> None:
            eng = engine_holder.get("engine")
            if not eng:
                return
            # Menu title -> ASR language tag; the model is multilingual, so
            # switching is instant with no model reload.
            for lang, mi in self.lang_items.items():
                if mi is item:
                    eng.cfg.language = lang
                    engine.LOGGER.info("language changed: %s", lang)
                    break

        def on_vocab_add(self, _item) -> None:
            # NOT rumps.Window: in an accessory (menu bar) app its modal can
            # open invisibly BEHIND other windows and freeze the main thread
            # (stuck "…" badge). The osascript dialog always comes frontmost.
            script = (
                'text returned of (display dialog '
                '"Term the ASR should spell exactly as written '
                '(e.g. MLX, PyPI, Wispr Flow):" '
                'default answer "" '
                'with title "parlando — add vocabulary term" '
                'buttons {"Cancel", "Add"} default button "Add")'
            )
            try:
                result = subprocess.run(
                    ["osascript", "-e", script],
                    capture_output=True,
                    text=True,
                    timeout=180,
                )
            except subprocess.TimeoutExpired:
                return
            if result.returncode != 0:
                return  # cancelled
            term = result.stdout.strip()
            if not term:
                return
            eng = engine_holder.get("engine")
            if eng is not None:
                # Active for the very next dictation; no restart needed.
                eng.add_vocab_term(term)

        def on_vocab_edit(self, _item) -> None:
            path = engine.VOCAB_FILE
            try:
                path.parent.mkdir(parents=True, exist_ok=True)
                if not path.exists():
                    path.write_text(
                        "# parlando vocabulary — one term per line.\n"
                        "# The ASR writes these exactly as spelled here.\n",
                        encoding="utf-8",
                    )
            except OSError:
                pass
            # -t: open in the default text editor. Saved edits are picked up
            # automatically at the next recording (mtime check).
            subprocess.run(["open", "-t", str(path)], check=False)

        def on_log(self, _item) -> None:
            subprocess.run(["open", str(engine.LOG_PATH)], check=False)

        def on_quit(self, _item) -> None:
            self._guard.stop()
            rumps.quit_application()

    app = ParlandoApp()

    def engine_thread() -> None:
        engine._setup_logging()
        eng = engine.DictationEngine(engine.Config())
        engine_holder["engine"] = eng
        try:
            asyncio.run(eng.run())
        except Exception:  # noqa: BLE001
            # rumps notifications need an app bundle; a log line is enough.
            engine.LOGGER.exception("engine crashed")
            print(
                f"[error] engine stopped — details: {engine.LOG_PATH}",
                file=sys.stderr,
            )

    threading.Thread(target=engine_thread, daemon=True).start()
    app.run()
    return 0


def main() -> int:
    if "--install-app" in sys.argv:
        return install_app()
    if "--uninstall-app" in sys.argv:
        return uninstall_app()
    if "--install-login" in sys.argv:
        return install_login()
    if "--uninstall-login" in sys.argv:
        return uninstall_login()
    return run_menubar()


if __name__ == "__main__":
    raise SystemExit(main())
