SETTINGS_PANES = {
    "accessibility": "x-apple.systempreferences:com.apple.preference.security?Privacy_Accessibility",
    "microphone": "x-apple.systempreferences:com.apple.preference.security?Privacy_Microphone",
}

_PROBLEM_TEXT = {
    "accessibility": (
        "Accessibility permission needed",
        "Hotkey and typing are off until Parlando is allowed; "
        "it reopens by itself if macOS quits it when you flip the switch",
        "Open Accessibility settings…",
    ),
    "microphone": (
        "Microphone is silent",
        "Allow Parlando under Microphone; it recovers by itself",
        "Open Microphone settings…",
    ),
}


def _tap_key(eng) -> str:
    """'right ⌥ Option' or the raw combo; '' when there is no hotkey."""
    key = eng.cfg.hotkey
    if not key:
        return ""
    return engine.TAP_KEY_LABELS.get(key, key)


def describe_status(eng) -> dict:
    """Turn engine state into what the menu shows.

    Returns: badge (text next to the icon), icon (idle/recording/paused),
    primary/secondary (the two status lines), action (problem key whose
    settings pane the third line opens, or None), toggle (title of the
    start/stop item), can_toggle.
    """
    st = eng.status
    lang = eng.cfg.language
    lang_badge = (
        "" if lang == engine.Config.language else LANGUAGE_BADGES.get(lang, "")
    )
    key = _tap_key(eng)
    tap = f"tap {key}" if key else "use the menu"
    words = f"{eng.total_words} words typed"
    asr = f" · ASR {eng.asr_ms:.0f} ms" if eng.asr_ms else ""
    out = dict(badge=lang_badge, icon="idle", action=None,
               toggle="Start recording", can_toggle=True)

    if st.phase == "downloading":
        pct = st.progress
        out.update(
            badge=f"{pct * 100:.0f}%" if pct is not None else "⬇",
            primary=("Downloading " + st.detail.split(" · ")[0]
                     + (f"… {pct * 100:.0f}%" if pct is not None else "…")),
            secondary=(f"{engine.human_bytes(st.downloaded)} of "
                       f"{engine.human_bytes(st.total)} · first run only"
                       if st.total else "First run only · this can take a few minutes"),
            toggle="Start recording", can_toggle=False,
        )
        return out
    if st.phase in ("starting", "loading"):
        out.update(
            badge="…",
            primary="Starting up…" if st.phase == "starting" else f"Loading {st.detail}…",
            secondary="Ready in a few seconds",
            can_toggle=False,
        )
        return out

    if st.problems:
        problem = st.problems[0]
        title, hint, _ = _PROBLEM_TEXT.get(problem, (problem, "", ""))
        out.update(badge="!", primary=f"⚠️ {title}", secondary=hint, action=problem)
        # The recording controls stay available (menu use works without
        # Accessibility; typing does not).
    elif st.phase == "recording":
        secs = eng.rec_samples / engine.SAMPLE_RATE
        out.update(primary=f"● Recording {secs:.0f} s",
                   secondary=f"Speak; {tap} again to stop and type")
    elif st.phase == "transcribing":
        out.update(badge="✎",
                   primary="Polishing…" if st.detail == "polishing" else "Transcribing…",
                   secondary="Typing into the focused window in a moment")
    elif st.phase == "paused":
        out.update(primary="Paused", secondary=f"Resume from the menu or {tap}")
    else:  # ready
        if eng.cfg.mode == "record":
            out.update(primary=f"Ready — {tap} to dictate", secondary=words + asr)
        else:
            live = "● Hearing speech" if eng.vad.in_speech else "Listening"
            out.update(primary=f"{live} — words appear as you speak",
                       secondary=words + asr)

    if eng.cfg.mode == "record":
        out["icon"] = "recording" if eng.recording else "idle"
        out["toggle"] = "Stop recording and type" if eng.recording else "Start recording"
        out["can_toggle"] = st.phase in ("ready", "recording")
    else:
        out["icon"] = ("paused" if eng.paused
                       else "recording" if eng.vad.in_speech else "idle")
        out["toggle"] = "Resume" if eng.paused else "Pause"
        out["can_toggle"] = True
    return out


